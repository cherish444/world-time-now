// 지원 언어 메타데이터. code는 URL 경로에 쓰이는 값(소문자-하이픈),
// locale은 Intl API에 넘길 BCP47 태그.
// en이 기본 언어라 URL에 prefix가 붙지 않는다 (예: /tokyo, 나머지는 /ko/tokyo).
