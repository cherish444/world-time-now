// 실제 접속 지역(IP 국가)과 기기/접속 타임존을 기반으로 언어 자동 감지 (브라우저 언어 세팅은 보지 않음)
export function detectLanguage({ country, timezone }) {
  if (country) {
    const l = langForCountry(country);
    if (l && l !== DEFAULT_LANG) return l;
  }
  if (timezone) {
    const l = langForTimezone(timezone);
    if (l && l !== DEFAULT_LANG) return l;
  }
  return DEFAULT_LANG;
}